def program6626():
    n = int(input()) % 360
    n -= 360 * (n >= 180)
    n += 360 * (n < -180)
    print(sorted([
        (abs(n - 0   + 360 * (n - 0   < -180)), 0),
        (abs(n - 90  + 360 * (n - 90  < -180)), 1),
        (abs(n - 180 + 360 * (n - 180 < -180)), 2),
        (abs(n - 270 + 360 * (n - 270 < -180)), 3)
    ])[0][1])