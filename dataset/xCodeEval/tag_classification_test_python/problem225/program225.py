def program225():
    a=list(map(int,input().strip().split()))[:14]
    i=0;ans=0
    while(i<14):
        dis=a[i]//14
        mod=a[i]%14
        b=a[:]
        res=0;j=1
        b[i]=0
        while(j<=14):
            x=b[(i+j)%14]
            x+=dis
            if(mod):
                x+=1
                mod-=1
            if(x%2==0):
                res+=x
            j+=1
        i+=1
        ans=max(ans,res)
    print(ans)