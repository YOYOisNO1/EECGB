def program2380():
    n=int(input())
    L=["+------------------------+",
       "|#.#.#.#.#.#.#.#.#.#.#.|D|)",
       "|#.#.#.#.#.#.#.#.#.#.#.|.|",
       "|#.......................|",
       "|#.#.#.#.#.#.#.#.#.#.#.|.|)",
       "+------------------------+"]
    L=[[ x for x in y] for y in L]
    for i in range(len(L[0])) :
        for j in range(len(L)) :
            if L[j][i]=="#" and n>0 :
                n-=1
                L[j][i]="O"
    for x in L :
        print("".join(x))