def program2567():
    l=input().split()
    n=int(l[0])
    a=int(l[1])
    x=int(l[2])
    b=int(l[3])
    y=int(l[4])
    l1=[a]
    l2=[b]
    while(l1[-1]!=x):
        if(l1[-1]==n):
            l1.append(1)
        else:
            z=l1[-1]
            l1.append(z+1)
    while(l2[-1]!=y):
        if(l2[-1]==1):
            l2.append(n)
        else:
            z=l2[-1]
            l2.append(z-1)
    poss=0
    for i in range(min(len(l1),len(l2))):
        if(l1[i]==l2[i]):
            poss=1
            break
    if(poss):
        print("YES")
    else:
        print("NO")